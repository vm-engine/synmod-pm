<?php

declare(strict_types=1);

namespace VmEngine\Pm\Services\Spk;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Throwable;
use VmEngine\Pm\Enums\Documents;
use VmEngine\Pm\Enums\ProposalStatus;
use VmEngine\Pm\Models\ProjectDocument;
use VmEngine\Pm\Models\ProjectSpk;
use VmEngine\Pm\Services\Proposal\Exceptions\ProposalValidationException;
use VmEngine\Pm\Services\Spk\Docx\DocxSpkRenderer;
use VmEngine\SynAuth\Facades\SynAuth;

/**
 * Publish: render PDF + DOCX and store them as the next SPK document version (same flow as SphPublisher).
 * The generated SPK is the unsigned draft, so the SPK "uploaded" hook (project → planning) is not fired.
 */
class SpkPublisher
{
    public function __construct(
        private readonly SpkValidator $validator,
        private readonly DocxSpkRenderer $docx,
        private readonly PdfSpkRenderer $pdf,
    ) {}

    public function publish(ProjectSpk $spk, int $userId): ProjectDocument
    {
        $spk->loadMissing('project.client', 'project.projectCategory', 'project.division');
        $errors = $this->validator->errors($spk);
        if ($errors !== []) {
            throw new ProposalValidationException($errors);
        }

        $written = [];

        try {
            return DB::transaction(function () use ($spk, $userId, &$written): ProjectDocument {
                $project = $spk->project;
                $handler = Documents::SPK->handler();
                if ($spk->number === null) {
                    $spk->number = $handler->generateDocumentNumber($project, Documents::SPK);
                    $handler->incrementIndex($project, Documents::SPK);
                }

                $version = (int) $project->documents()->byType(Documents::SPK)->max('version') + 1;
                $data = SpkDocumentData::build($spk);
                $directory = 'projects/'.$project->id.'/documents/spk';
                $name = 'spk_'.Str::slug(str_replace('/', '-', (string) $spk->number)).'_v'.$version;

                $pdfPath = $directory.'/'.$name.'.pdf';
                Storage::disk('local')->put($pdfPath, $this->pdf->render($data));
                $written[] = $pdfPath;

                $docxPath = $directory.'/'.$name.'.docx';
                $base = (string) tempnam(sys_get_temp_dir(), 'spk');
                $temp = $base.'.docx';
                try {
                    $this->docx->render($data, $temp);
                    Storage::disk('local')->put($docxPath, (string) file_get_contents($temp));
                    $written[] = $docxPath;
                } finally {
                    @unlink($temp);
                    @unlink($base);
                }

                $document = ProjectDocument::create([
                    'user_id' => $userId,
                    'project_id' => $project->id,
                    'client_id' => $project->client_id,
                    'type' => Documents::SPK->value,
                    'number' => $spk->number,
                    'notes' => 'Generated by SPK Generator',
                    'file_path' => $pdfPath,
                    'file_info' => [
                        'original_name' => $name.'.pdf',
                        'size' => Storage::disk('local')->size($pdfPath),
                        'mime_type' => 'application/pdf',
                        'docx' => $docxPath,
                        'docx_name' => $name.'.docx',
                    ],
                    'version' => $version,
                    'created_by' => $userId,
                ]);

                $spk->forceFill([
                    'status' => ProposalStatus::Published,
                    'published_snapshot' => $spk->only(ProjectSpk::CONTENT_FIELDS),
                    'published_version' => $version,
                    'published_at' => now(),
                    'published_by' => $userId,
                ])->save();
                $spk->forceFill(['has_unpublished_changes' => false])->saveQuietly();

                $project->forceFill(['nominal' => $spk->contract_value])->save();

                SynAuth::logActivity(
                    $userId,
                    'pm.project.'.$project->id.'.spk.publish',
                    'Published SPK '.$spk->number.' as version '.$version,
                    'project.'.$project->id.'.spk',
                    'pm',
                );

                return $document;
            });
        } catch (Throwable $e) {
            foreach ($written as $path) {
                Storage::disk('local')->delete($path);
            }
            $spk->refresh();

            throw $e;
        }
    }
}
