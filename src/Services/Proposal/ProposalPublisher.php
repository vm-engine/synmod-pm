<?php

declare(strict_types=1);

namespace VmEngine\Pm\Services\Proposal;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Throwable;
use VmEngine\Pm\Enums\Documents;
use VmEngine\Pm\Enums\ProposalStatus;
use VmEngine\Pm\Models\ProjectDocument;
use VmEngine\Pm\Models\ProjectProposal;
use VmEngine\Pm\Services\Proposal\Exceptions\ProposalValidationException;
use VmEngine\Pm\Services\Proposal\Pptx\PptxProposalRenderer;
use VmEngine\SynAuth\Facades\SynAuth;

/**
 * Publish = approved (spec §7): render both files and store them as the next PROPOSAL document version.
 */
class ProposalPublisher
{
    public function __construct(
        private readonly ProposalValidator $validator,
        private readonly PptxProposalRenderer $pptx,
        private readonly PdfProposalRenderer $pdf,
    ) {}

    public function publish(ProjectProposal $proposal, int $userId): ProjectDocument
    {
        $proposal->loadMissing('project.client', 'project.projectCategory', 'project.division');
        $errors = $this->validator->errors($proposal);
        if ($errors !== []) {
            throw new ProposalValidationException($errors);
        }

        $written = [];

        try {
            return DB::transaction(function () use ($proposal, $userId, &$written): ProjectDocument {
                $project = $proposal->project;
                $handler = Documents::PROPOSAL->handler();
                if ($proposal->number === null) {
                    $proposal->number = $handler->generateDocumentNumber($project, Documents::PROPOSAL);
                    $handler->incrementIndex($project, Documents::PROPOSAL);
                }

                $version = (int) $project->documents()->byType(Documents::PROPOSAL)->max('version') + 1;
                $data = ProposalDocumentData::build($proposal);
                $directory = 'projects/'.$project->id.'/documents/proposal';
                $name = 'proposal_'.Str::slug(str_replace('/', '-', (string) $proposal->number)).'_v'.$version;

                $pdfPath = $directory.'/'.$name.'.pdf';
                Storage::disk('local')->put($pdfPath, $this->pdf->render($data));
                $written[] = $pdfPath;

                $pptxPath = $directory.'/'.$name.'.pptx';
                $temp = tempnam(sys_get_temp_dir(), 'proposal').'.pptx';
                try {
                    $this->pptx->render($data, $temp);
                    Storage::disk('local')->put($pptxPath, (string) file_get_contents($temp));
                    $written[] = $pptxPath;
                } finally {
                    @unlink($temp);
                }

                $document = ProjectDocument::create([
                    'user_id' => $userId,
                    'project_id' => $project->id,
                    'client_id' => $project->client_id,
                    'type' => Documents::PROPOSAL->value,
                    'number' => $proposal->number,
                    'notes' => 'Generated by Proposal Generator',
                    'file_path' => $pdfPath,
                    'file_info' => [
                        'original_name' => $name.'.pdf',
                        'size' => Storage::disk('local')->size($pdfPath),
                        'mime_type' => 'application/pdf',
                        'pptx' => $pptxPath,
                        'pptx_name' => $name.'.pptx',
                    ],
                    'version' => $version,
                    'created_by' => $userId,
                ]);

                $proposal->forceFill([
                    'status' => ProposalStatus::Published,
                    'published_snapshot' => $proposal->only(ProjectProposal::CONTENT_FIELDS),
                    'published_version' => $version,
                    'published_at' => now(),
                    'published_by' => $userId,
                ])->save();
                $proposal->forceFill(['has_unpublished_changes' => false])->saveQuietly();

                $project->forceFill(['nominal' => $proposal->grand_total])->save();

                SynAuth::logActivity(
                    $userId,
                    'pm.project.'.$project->id.'.proposal.publish',
                    'Published proposal '.$proposal->number.' as version '.$version,
                    'project.'.$project->id.'.proposal',
                    'pm',
                );

                return $document;
            });
        } catch (Throwable $e) {
            foreach ($written as $path) {
                Storage::disk('local')->delete($path);
            }
            $proposal->refresh();

            throw $e;
        }
    }
}
