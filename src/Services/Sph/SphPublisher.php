<?php

declare(strict_types=1);

namespace VmEngine\Pm\Services\Sph;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Storage;
use Illuminate\Support\Str;
use Throwable;
use VmEngine\Pm\Enums\Documents;
use VmEngine\Pm\Enums\ProposalStatus;
use VmEngine\Pm\Models\ProjectDocument;
use VmEngine\Pm\Models\ProjectSph;
use VmEngine\Pm\Services\Proposal\Exceptions\ProposalValidationException;
use VmEngine\Pm\Services\Sph\Docx\DocxSphRenderer;
use VmEngine\SynAuth\Facades\SynAuth;

/**
 * Publish: render PDF + DOCX and store them as the next SPH document version (same flow as ProposalPublisher).
 */
class SphPublisher
{
    public function __construct(
        private readonly SphValidator $validator,
        private readonly DocxSphRenderer $docx,
        private readonly PdfSphRenderer $pdf,
    ) {}

    public function publish(ProjectSph $sph, int $userId): ProjectDocument
    {
        $sph->loadMissing('project.client', 'project.projectCategory', 'project.division');
        $errors = $this->validator->errors($sph);
        if ($errors !== []) {
            throw new ProposalValidationException($errors);
        }

        $written = [];

        try {
            return DB::transaction(function () use ($sph, $userId, &$written): ProjectDocument {
                $project = $sph->project;
                $handler = Documents::SPH->handler();
                if ($sph->number === null) {
                    $sph->number = $handler->generateDocumentNumber($project, Documents::SPH);
                    $handler->incrementIndex($project, Documents::SPH);
                }

                $version = (int) $project->documents()->byType(Documents::SPH)->max('version') + 1;
                $data = SphDocumentData::build($sph);
                $directory = 'projects/'.$project->id.'/documents/sph';
                $name = 'sph_'.Str::slug(str_replace('/', '-', (string) $sph->number)).'_v'.$version;

                $pdfPath = $directory.'/'.$name.'.pdf';
                Storage::disk('local')->put($pdfPath, $this->pdf->render($data));
                $written[] = $pdfPath;

                $docxPath = $directory.'/'.$name.'.docx';
                $base = (string) tempnam(sys_get_temp_dir(), 'sph');
                $temp = $base.'.docx';
                try {
                    $this->docx->render($data, $temp);
                    Storage::disk('local')->put($docxPath, (string) file_get_contents($temp));
                    $written[] = $docxPath;
                } finally {
                    @unlink($temp);
                    @unlink($base);
                }

                $document = ProjectDocument::create([
                    'user_id' => $userId,
                    'project_id' => $project->id,
                    'client_id' => $project->client_id,
                    'type' => Documents::SPH->value,
                    'number' => $sph->number,
                    'notes' => 'Generated by SPH Generator',
                    'file_path' => $pdfPath,
                    'file_info' => [
                        'original_name' => $name.'.pdf',
                        'size' => Storage::disk('local')->size($pdfPath),
                        'mime_type' => 'application/pdf',
                        'docx' => $docxPath,
                        'docx_name' => $name.'.docx',
                    ],
                    'version' => $version,
                    'created_by' => $userId,
                ]);

                $sph->forceFill([
                    'status' => ProposalStatus::Published,
                    'published_snapshot' => $sph->only(ProjectSph::CONTENT_FIELDS),
                    'published_version' => $version,
                    'published_at' => now(),
                    'published_by' => $userId,
                ])->save();
                $sph->forceFill(['has_unpublished_changes' => false])->saveQuietly();

                $project->forceFill(['nominal' => $sph->grand_total])->save();

                SynAuth::logActivity(
                    $userId,
                    'pm.project.'.$project->id.'.sph.publish',
                    'Published SPH '.$sph->number.' as version '.$version,
                    'project.'.$project->id.'.sph',
                    'pm',
                );

                return $document;
            });
        } catch (Throwable $e) {
            foreach ($written as $path) {
                Storage::disk('local')->delete($path);
            }
            $sph->refresh();

            throw $e;
        }
    }
}
